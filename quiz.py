"""Comprehension Check: short section quizzes built only from approved claims the successor may see.

Questions are generated by plain rules, stored once per share so the answer key never changes under the
successor, and never use a claim above their clearance. Wrong answers show the cited source passage.
"""

import json
import random
import re
from datetime import datetime

import pipeline
from db import now, one, query, run, run_all
from linking import CONTACT_NAME

PASS_MARK = 0.8
MAX_QUESTIONS = 5
SNIPPET = 150
BLANK = "_____"
ISO = re.compile(r"\b\d{4}-\d{2}-\d{2}\b")
TIME_FORMAT = "%Y-%m-%d %H:%M:%S"


def section_titles():
    return [title for title, _ in pipeline.SECTIONS]


def snippet(text, limit=SNIPPET):
    text = " ".join((text or "").split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "\u2026"


def eligible(project_id, clearance):
    return query(
        "SELECT c.*, s.filename FROM claims c JOIN sources s ON s.id = c.source_id WHERE c.project_id = ? "
        "AND c.status = 'approved' AND c.access_rank <= ? ORDER BY c.id", (project_id, clearance))


def _names(claims):
    names = {claim["owner"] for claim in claims if claim["owner"]}
    for claim in claims:
        names.update(match.group(1) for match in CONTACT_NAME.finditer(claim["statement"]))
    return sorted(names)


def generate(project_id, clearance, share_id):
    """{section title: [question dicts]} for this share. Deterministic for a given share."""
    claims = eligible(project_id, clearance)
    names, dates = _names(claims), sorted({d for claim in claims for d in ISO.findall(claim["statement"])})
    owners_by_area = {}
    for claim in claims:
        if claim["owner"] and claim["area"]:
            owners_by_area.setdefault(claim["area"], set()).add(claim["owner"])
    contested = {area for area, who in owners_by_area.items() if len(who) > 1}

    def mentions_contested(text):
        flat = " ".join(re.sub(r"[^\w\s]", "", text.lower()).split())
        return any(area in flat for area in contested)
    quiz = {}
    for title, kinds in pipeline.SECTIONS:
        items = [claim for claim in claims if claim["type"] in kinds]
        if not items:
            continue
        rng = random.Random(f"{share_id}:{title}")  # nosec B311 - a seeded shuffle for repeatable quizzes, not a security use
        others = [claim for claim in claims if claim["type"] not in kinds]
        questions, seen_text, used = [], set(), set()

        def add(question, correct, wrong, claim):
            wrong = [item for item in dict.fromkeys(wrong) if item != correct]
            if question in seen_text or not wrong or len(questions) >= MAX_QUESTIONS:
                return False
            options = [correct, *wrong[:3]]
            rng.shuffle(options)
            seen_text.add(question)
            used.add(claim["id"])
            questions.append({"question": question, "options": options, "correct_index": options.index(correct), "claim_id": claim["id"]})
            return True

        for claim in items:
            if claim["grade"] == "Conflicting" or mentions_contested(claim["statement"]):
                continue
            if claim["owner"] and claim["area"] and claim["type"] == "responsibility" and len(names) >= 2:
                pool = [name for name in names if name != claim["owner"]]
                add(f"Who owns {claim['area']}?", claim["owner"], rng.sample(pool, min(3, len(pool))), claim)
                continue
            found = next((name for name in names if re.search(r"(?<!\w)" + re.escape(name) + r"(?!\w)", claim["statement"])), None)
            if found and len(names) >= 2:
                text = re.sub(r"(?<!\w)" + re.escape(found) + r"(?!\w)", BLANK, claim["statement"])
                if BLANK in snippet(text, 220):
                    pool = [name for name in names if name != found]
                    add(f"Fill in the blank: \u201c{snippet(text, 220)}\u201d", found, rng.sample(pool, min(3, len(pool))), claim)
                    continue
            when = ISO.search(claim["statement"])
            if when and len(dates) >= 2:
                text = claim["statement"].replace(when.group(), BLANK)
                if BLANK in snippet(text, 220):
                    pool = [d for d in dates if d != when.group()]
                    add(f"Fill in the blank: \u201c{snippet(text, 220)}\u201d", when.group(), rng.sample(pool, min(3, len(pool))), claim)
        for claim in items:
            if len(questions) >= MAX_QUESTIONS:
                break
            if claim["id"] in used or claim["grade"] == "Conflicting":
                continue
            correct = snippet(claim["statement"])
            pool = [snippet(other["statement"]) for other in (others or [c for c in items if c["id"] != claim["id"]])]
            pool = [text for text in dict.fromkeys(pool) if text != correct]
            add(f"Which of these is recorded under \u201c{title}\u201d?", correct, rng.sample(pool, min(3, len(pool))), claim)
        quiz[title] = questions
    return quiz


def ensure_quiz(share_id, project_id, clearance):
    """Create and store this share's questions once. Later calls reuse them."""
    have = {row["section"] for row in query("SELECT DISTINCT section FROM quiz_questions WHERE share_id = ?", (share_id,))}
    wanted = [title for title, items in pipeline.plan_sections(project_id, clearance)]
    if all(title in have for title in wanted if title):
        return
    generated = generate(project_id, clearance, share_id)
    statements = []
    for title, questions in generated.items():
        if title in have:
            continue
        for position, item in enumerate(questions):
            statements.append((
                "INSERT INTO quiz_questions(share_id, section, position, question, options, correct_index, claim_id, created_at) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                (share_id, title, position, item["question"], json.dumps(item["options"]), item["correct_index"], item["claim_id"], now())))
    if statements:
        run_all(statements)


def questions_for(share_id, title):
    rows = query("SELECT * FROM quiz_questions WHERE share_id = ? AND section = ? ORDER BY position", (share_id, title))
    return [dict(row) | {"options": json.loads(row["options"])} for row in rows]


def start_attempt(share_id, title):
    open_one = one("SELECT * FROM quiz_attempts WHERE share_id = ? AND section = ? AND submitted_at IS NULL ORDER BY id DESC", (share_id, title))
    if open_one:
        return open_one["id"]
    return run("INSERT INTO quiz_attempts(share_id, section, started_at) VALUES (?, ?, ?)", (share_id, title, now()))


def submit(share_id, title, answers):
    """Score one attempt. `answers` maps question id to the chosen option index."""
    questions = questions_for(share_id, title)
    attempt_id = start_attempt(share_id, title)
    attempt = one("SELECT * FROM quiz_attempts WHERE id = ?", (attempt_id,))
    graded, correct = [], 0
    for question in questions:
        chosen = answers.get(question["id"])
        good = chosen == question["correct_index"]
        correct += int(good)
        claim = one("SELECT c.*, s.filename FROM claims c JOIN sources s ON s.id = c.source_id WHERE c.id = ?", (question["claim_id"],))
        graded.append({"question": question, "chosen": chosen, "correct": good, "claim": claim})
    total = len(questions)
    passed = bool(total) and correct / total >= PASS_MARK
    seconds = max(0, int((datetime.strptime(now(), TIME_FORMAT) - datetime.strptime(attempt["started_at"], TIME_FORMAT)).total_seconds()))
    run_all(
        [("UPDATE quiz_attempts SET submitted_at = ?, total = ?, correct = ?, passed = ?, seconds = ? WHERE id = ?",
          (now(), total, correct, int(passed), seconds, attempt_id))]
        + [("INSERT INTO quiz_answers(attempt_id, question_id, chosen_index, is_correct) VALUES (?, ?, ?, ?)",
            (attempt_id, item["question"]["id"], -1 if item["chosen"] is None else item["chosen"], int(item["correct"]))) for item in graded])
    return {"attempt_id": attempt_id, "total": total, "correct": correct, "passed": passed, "seconds": seconds, "graded": graded}


def can_acknowledge(share_id, title):
    if not questions_for(share_id, title):
        return True
    return bool(one("SELECT 1 FROM quiz_attempts WHERE share_id = ? AND section = ? AND passed = 1", (share_id, title)))


def acknowledge_section(share_id, title):
    run("INSERT OR IGNORE INTO section_acks(share_id, section, acked_at) VALUES (?, ?, ?)", (share_id, title, now()))


def section_status(share_id, project_id, clearance):
    ensure_quiz(share_id, project_id, clearance)
    acked = {row["section"] for row in query("SELECT section FROM section_acks WHERE share_id = ?", (share_id,))}
    result = []
    for index, (title, kinds) in enumerate(pipeline.SECTIONS):
        items = [item for t, group in pipeline.plan_sections(project_id, clearance) if t == title for item in group]
        if not items:
            continue
        total = len(questions_for(share_id, title))
        attempts = query("SELECT * FROM quiz_attempts WHERE share_id = ? AND section = ? AND submitted_at IS NOT NULL ORDER BY id", (share_id, title))
        best = max(attempts, key=lambda row: (row["correct"], -row["seconds"]), default=None)
        if title in acked:
            state = "done"
        elif not total:
            state = "no_check"
        elif any(row["passed"] for row in attempts):
            state = "passed"
        elif attempts:
            state = "retry"
        else:
            state = "todo"
        result.append({"index": index, "title": title, "state": state, "questions": total,
                       "best": (best["correct"], best["total"]) if best else None, "attempts": len(attempts)})
    return result


def all_acknowledged(share_id, project_id, clearance):
    statuses = section_status(share_id, project_id, clearance)
    return all(item["state"] == "done" for item in statuses), statuses


def reviewer_report(project_id):
    """Scores, time and the most-missed questions, across every share of this project."""
    if not one("SELECT 1 FROM shares WHERE project_id = ?", (project_id,)):
        return {"sections": [], "missed": [], "attempts": 0}
    sections = []
    for title in section_titles():
        rows = query(
            "SELECT a.* FROM quiz_attempts a JOIN shares s ON s.id = a.share_id "
            "WHERE s.project_id = ? AND a.section = ? AND a.submitted_at IS NOT NULL", (project_id, title))
        asked = one("SELECT 1 FROM quiz_questions q JOIN shares s ON s.id = q.share_id WHERE s.project_id = ? AND q.section = ? LIMIT 1",
                    (project_id, title))
        if not rows and not asked:
            continue
        acked = one("SELECT COUNT(*) AS n FROM section_acks k JOIN shares s ON s.id = k.share_id WHERE s.project_id = ? AND k.section = ?",
                    (project_id, title))["n"]
        sections.append({
            "title": title, "attempts": len(rows), "passed": sum(1 for row in rows if row["passed"]), "acked": acked,
            "best": max((round(100 * row["correct"] / row["total"]) for row in rows if row["total"]), default=None),
            "average_seconds": round(sum(row["seconds"] for row in rows) / len(rows)) if rows else None})
    missed = query(
        "SELECT q.id, q.section, q.question, q.options, q.correct_index, COUNT(*) AS tries, SUM(1 - a.is_correct) AS misses "
        "FROM quiz_answers a JOIN quiz_questions q ON q.id = a.question_id JOIN shares s ON s.id = q.share_id "
        "WHERE s.project_id = ? GROUP BY q.id HAVING misses > 0 ORDER BY misses DESC, tries DESC, q.id LIMIT 8", (project_id,))
    attempts = one("SELECT COUNT(*) AS n FROM quiz_attempts a JOIN shares s ON s.id = a.share_id "
                   "WHERE s.project_id = ? AND a.submitted_at IS NOT NULL", (project_id,))["n"]
    return {"sections": sections, "attempts": attempts,
            "missed": [dict(row) | {"options": json.loads(row["options"])} for row in missed]}
